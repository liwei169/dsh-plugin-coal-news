const CCOAL_EXCLUDE = /投稿|订阅|广告|招聘|声明|启事|受贿|违纪|腐败|非法收受|被查|落马|双开|开除党籍/;

/** 中国煤炭报 lists: col2058.html, col2058_2.html, col2058_3.html, … */
function ccoalPage(url, index) {
  return url.replace(/\.html$/, `_${index + 1}.html`);
}

/** 矿山安监局 / TRS lists: /xw/mkaqjcxw/, index_1.shtml, index_2.shtml, … */
function trsPage(url, index) {
  return `${url}index_${index}.shtml`;
}

